import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import ts from "typescript";
import prettier from "prettier";

export async function generateEngineeringMap(root, { write = false } = {}) {
  const readJson = (path) => JSON.parse(readFileSync(resolve(root, path), "utf8"));
  const areas = readJson("docs/engineering-map.json");
  const { scripts, workspaces } = readJson("package.json");
  const errors = [];
  const requirePath = (path) => {
    const absolute = resolve(root, path);
    if (relative(root, absolute).startsWith("..") || !existsSync(absolute)) {
      errors.push(`Missing or out-of-repository path: ${path}`);
    }
    return absolute;
  };
  const modules = areas.flatMap((area) => area.interfaces.map(({ module }) => requirePath(module)));
  const configPath = requirePath("tsconfig.json");
  const config = ts.readConfigFile(configPath, ts.sys.readFile);
  if (config.error)
    throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, "\n"));
  const { options } = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
  const program = ts.createProgram(modules, { ...options, noEmit: true });
  const checker = program.getTypeChecker();
  const titles = new Set();
  for (const area of areas) {
    if (titles.has(area.title)) errors.push(`Duplicate area: ${area.title}`);
    titles.add(area.title);
    requirePath(area.spec);
    for (const owner of area.owners) requirePath(owner);
    for (const { module, symbols } of area.interfaces) {
      const source = program.getSourceFile(resolve(root, module));
      const symbol = source && checker.getSymbolAtLocation(source);
      const exports = new Set(
        symbol
          ? checker
              .getExportsOfModule(symbol)
              .filter((item) => {
                const target =
                  item.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(item) : item;
                return target.declarations?.length;
              })
              .map((item) => item.name)
          : [],
      );
      for (const name of symbols) {
        if (!exports.has(name)) errors.push(`Missing export: ${module} -> ${name}`);
      }
    }
    for (const command of area.checks) {
      if (!scripts[command]) errors.push(`Missing npm script: ${command}`);
    }
  }
  // Derive package boundaries from the workspace manifests, rather than keeping
  // a second manually maintained list of supported import paths.
  const { globSync } = await import("node:fs");
  const packages = globSync(
    workspaces.map((workspace) => `${workspace}/package.json`),
    { cwd: root },
  )
    .sort()
    .map((path) => ({ path, ...readJson(path) }));
  const publicEntries = [];
  for (const pkg of packages) {
    for (const [subpath, target] of Object.entries(pkg.exports ?? {})) {
      if (typeof target !== "string") {
        errors.push(
          `Unsupported conditional export in ${pkg.path}: ${subpath}; extend the generator.`,
        );
        continue;
      }
      const path = relative(root, resolve(root, dirname(pkg.path), target));
      requirePath(path);
      publicEntries.push(
        `| \`${pkg.name}${subpath === "." ? "" : subpath.slice(1)}\` | [\`${path}\`](../${path}) |`,
      );
    }
  }
  // Check local executable references in mapped commands, including nested npm run
  // commands. This validates routing, not whether a check will pass when executed.
  const visited = new Set();
  function checkCommand(name, commands = scripts, base = "") {
    const key = `${base}:${name}`;
    if (visited.has(key)) return;
    visited.add(key);
    const command = commands[name];
    if (!command) {
      errors.push(`Missing npm script: ${name}`);
      return;
    }
    for (const match of command.matchAll(/\bnode\s+((?:scripts|tests)\/[^\s;&]+)/g))
      requirePath(`${base}${match[1]}`);
    for (const match of command.matchAll(
      /\bnpm run ([\w:-]+)(?: --workspace(?:=| )([^\s;&]+))?/g,
    )) {
      if (!match[2]) {
        checkCommand(match[1], commands, base);
        continue;
      }
      const workspace = packages.find((pkg) => pkg.name === match[2]);
      if (!workspace) errors.push(`Missing workspace: ${match[2]}`);
      else checkCommand(match[1], workspace.scripts ?? {}, `${dirname(workspace.path)}/`);
    }
  }
  for (const area of areas) for (const command of area.checks) checkCommand(command);
  if (errors.length) throw new Error(`Engineering map validation failed:\n${errors.join("\n")}`);

  const link = (path) => `[\`${path}\`](../${path})`;
  let markdown = `# Engineering map

<!-- Generated by npm run map:generate; edit docs/engineering-map.json and scripts/engineering-map/generate.mjs. -->

Use this map when ownership or cross-file behavior is unclear.
[PRODUCT_SPEC.md](../PRODUCT_SPEC.md) and its linked specifications
remain authoritative. This is a routing guide, not another behavior specification
or an exhaustive source inventory. Owner paths are implementation entry points;
only the package imports listed at the end are cross-package consumer interfaces.
Web-local exports listed below are seams within the web application.

## Keeping the map current

In the same change that moves ownership, renames a mapped module/export, changes a
boundary or invariant, or replaces a verification command, review the affected
area in [engineering-map.json](engineering-map.json), update the authoritative
product spec when behavior changes, and run \`npm run map:generate\`.
Review adjacent areas when splitting a controller or moving responsibilities.
Run \`npm run verify:map\` before committing; it is also part of \`verify:fast\`.

The check validates mapped paths, TypeScript exports (including re-exports), npm
script names and their local Node script targets, package export targets, and exact
generated output. It does **not** prove that ownership descriptions or invariant
prose remain semantically current, that the selected checks are sufficient, or
that those checks pass. A still-existing module can stop owning a responsibility;
architecture review must catch that even when freshness validation passes.

## Area routes

Check selection follows [AGENTS.md](../AGENTS.md#workflow). The area checks below
are available commands, not a mandatory sequence; invoke each with \`npm run\`.
Read the delivery contract for prerequisites and evidence flags; \`home:evidence\`
needs a running preview, and panel builds normally require a committed tree.

`;
  for (const area of areas) {
    markdown += `### ${area.title}\n\n`;
    markdown += `Contract: [${area.title}](../${area.spec}).\n\n`;
    markdown += `- Owners: ${area.owners.map(link).join(", ")}.\n`;
    markdown += `- Interface: ${area.interfaces.length ? area.interfaces.map(({ module, symbols }) => `${symbols.map((name) => `\`${name}\``).join(", ")} via ${link(module)}`).join("; ") : "repository commands below"}.\n`;
    markdown += `- Review invariant: ${area.invariant}\n`;
    markdown += `- Checks: ${area.checks.map((name) => `\`${name}\``).join(", ")}.\n\n`;
  }
  markdown += `## Package import boundaries\n\nDerived from workspace \`package.json\` exports. These are import entry points,\nnot permission to edit stable packages during home generation. Consult the area\nabove for the supported symbols relevant to the task.\n\n| Import | Source |\n| --- | --- |\n${publicEntries.join("\n")}\n`;
  const output = resolve(root, "docs/engineering-map.md");
  const formatted = await prettier.format(markdown, {
    ...(await prettier.resolveConfig(output)),
    filepath: output,
  });
  if (write) {
    writeFileSync(output, formatted);
    console.log(`Generated ${relative(root, output)} (${areas.length} areas).`);
  } else if (!existsSync(output) || readFileSync(output, "utf8") !== formatted) {
    throw new Error("Engineering map is stale. Run npm run map:generate and review the diff.");
  } else {
    console.log(
      `Engineering map verified (${areas.length} areas, ${publicEntries.length} package imports).`,
    );
  }
}
